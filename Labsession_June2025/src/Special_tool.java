import java.util.*;
public class Special_tool {
    public static void main(String[] args) {
        Scanner msc = new Scanner(System.in);
        System.out.print("Enter a Number to Compare: ");
        int n = msc.nextInt();
        int m = msc.nextInt();
        System.out.println(m+">"+n+" is "+(m>n));
        System.out.println(m+">="+n+" is "+(m>=n));
        System.out.println(m+">"+n+" is "+(m>n));
        System.out.println(m+"<="+n+" is "+(m<=n));
        System.out.println(m+"=="+n+" is "+(m==n));
        System.out.println(m+"!="+n+" is "+(m!=n));


    }
}
